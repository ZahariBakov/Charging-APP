# Builds dist/Index.html: src/index.html with style.css, media.css and script.js inlined.
# Apps Script can only serve HTML files, so the app has to reach it as one file.
#
# Usage (from the project folder):   powershell -ExecutionPolicy Bypass -File .\build.ps1

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$src = Join-Path $root 'src'
$dist = Join-Path $root 'dist'
$utf8 = New-Object Text.UTF8Encoding $false

# Line endings are normalized to LF, so the output is the same on every computer
function Read-Source($name) {
  [IO.File]::ReadAllText((Join-Path $src $name), $utf8).Replace("`r`n", "`n")
}

function Indent($text) {
  ($text.TrimEnd() -split "`r?`n" | ForEach-Object { if ($_) { "  $_" } else { '' } }) -join "`n"
}

# Replaces one tag in the page, failing loudly if it is missing so a broken build never ships
function Inline([string]$page, [string]$tag, [string]$open, [string]$content, [string]$close) {
  if (-not $page.Contains($tag)) { throw "build.ps1: '$tag' not found in src/index.html" }
  if ($content -match [regex]::Escape($close)) { throw "build.ps1: $close found inside inlined file" }
  $page.Replace($tag, "$open`n$(Indent $content)`n$close")
}

$page = Read-Source 'index.html'
$page = Inline $page '<link rel="stylesheet" href="style.css" />' '<style>' (Read-Source 'style.css') '</style>'
$page = Inline $page '<link rel="stylesheet" href="media.css" />' '<style>' (Read-Source 'media.css') '</style>'
$page = Inline $page '<script src="script.js"></script>' '<script>' (Read-Source 'script.js') '</script>'

$banner = "<!-- Generated by build.ps1 from src/. Do not edit this file; edit src/ and run the build. -->`n"
New-Item -ItemType Directory -Force $dist | Out-Null
$out = Join-Path $dist 'Index.html'
[IO.File]::WriteAllText($out, $page.Replace("<!DOCTYPE html>`n", "<!DOCTYPE html>`n$banner"), $utf8)

$size = [math]::Round((Get-Item $out).Length / 1KB, 1)
Write-Host "Built dist/Index.html ($size KB)"
